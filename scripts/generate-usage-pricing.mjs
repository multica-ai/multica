#!/usr/bin/env node
// Regenerates the TypeScript pricing module from the server-embedded protocol
// document. CI can rerun this command and fail on a diff, preventing rate drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(repoRoot, "server/internal/handler/usage_pricing_v1.json");
const targetPath = resolve(repoRoot, "packages/core/runtimes/usage-pricing.ts");
const catalog = JSON.parse(readFileSync(sourcePath, "utf8"));

if (catalog.version !== "1" || catalog.units?.rates !== "usd_per_million_tokens") {
  throw new Error("usage_pricing_v1.json: unsupported version or rate unit");
}
if (!catalog.models || typeof catalog.models !== "object") {
  throw new Error('usage_pricing_v1.json: expected a top-level "models" object');
}

const generated = `// AUTO-GENERATED by scripts/generate-usage-pricing.mjs.\n` +
  `// Do not edit by hand — edit server/internal/handler/usage_pricing_v1.json\n` +
  `// and run \`pnpm generate:usage-pricing\`.\n\n` +
  `export const USAGE_PRICING_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n\n` +
  `export type UsageModelPricing = {\n` +
  `  input: number;\n  output: number;\n  cacheRead: number;\n  cacheWrite: number;\n};\n\n` +
  `export const MODEL_PRICING: Readonly<Record<string, UsageModelPricing>> =\n` +
  `  Object.fromEntries(Object.entries(USAGE_PRICING_CATALOG.models).map(\n` +
  `    ([key, rate]) => [key, {\n` +
  `      input: rate.input,\n      output: rate.output,\n` +
  `      cacheRead: rate.cache_read,\n      cacheWrite: rate.cache_write,\n` +
  `    }],\n  ));\n`;

writeFileSync(targetPath, generated);
