#!/usr/bin/env node
// Regenerates the Go and TypeScript text-preview lookup tables from
// server/internal/handler/text_preview_types.json (the single source of truth).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(
  repoRoot,
  "server/internal/handler/text_preview_types.json",
);
const goPath = resolve(
  repoRoot,
  "server/internal/handler/text_preview_types_generated.go",
);
const tsPath = resolve(
  repoRoot,
  "packages/views/editor/utils/text-preview-types.generated.ts",
);

const sourceName = "text_preview_types.json";
const data = JSON.parse(readFileSync(jsonPath, "utf8"));

const contentTypes = validateStringArray(data.contentTypes, "contentTypes", {
  validate(value) {
    return value.includes("/") && !value.includes(";");
  },
  expectation: "lowercase MIME types without parameters",
});
const extensionGroups = validateGroups(
  data.extensionGroups,
  "extensionGroups",
  "extensions",
  {
    validate(value) {
      return (
        !value.includes(".") &&
        !value.includes("/") &&
        !value.includes("\\")
      );
    },
    expectation: "extensions without dots or path separators",
  },
);
const basenameGroups = validateGroups(
  data.basenameGroups,
  "basenameGroups",
  "basenames",
  {
    validate(value) {
      return !value.includes("/") && !value.includes("\\");
    },
    expectation: "basenames without path separators",
  },
);

writeFileSync(goPath, generateGo());
writeFileSync(tsPath, generateTypeScript());

function validateGroups(groups, field, valuesField, options) {
  if (!Array.isArray(groups)) {
    throw new Error(
      `${sourceName}: expected top-level ${JSON.stringify(field)} array`,
    );
  }

  const seen = new Set();
  return groups.map((group, index) => {
    if (!group || typeof group !== "object") {
      throw new Error(`${sourceName}: ${field}[${index}] must be an object`);
    }
    if (typeof group.label !== "string" || group.label.trim() === "") {
      throw new Error(
        `${sourceName}: ${field}[${index}].label must be a non-empty string`,
      );
    }
    if (typeof group.language !== "string" || group.language.trim() === "") {
      throw new Error(
        `${sourceName}: ${field}[${index}].language must be a non-empty string`,
      );
    }

    const values = validateStringArray(
      group[valuesField],
      `${field}[${index}].${valuesField}`,
      options,
    );
    for (const value of values) {
      if (seen.has(value)) {
        throw new Error(
          `${sourceName}: duplicate ${valuesField} entry ${JSON.stringify(value)}`,
        );
      }
      seen.add(value);
    }
    return {
      label: group.label.trim(),
      language: group.language.trim(),
      values,
    };
  });
}

function validateStringArray(value, field, options) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error(`${sourceName}: ${field} must be a non-empty array`);
  }

  const seen = new Set();
  return value.map((entry, index) => {
    if (
      typeof entry !== "string" ||
      entry === "" ||
      entry !== entry.trim() ||
      entry !== entry.toLowerCase()
    ) {
      throw new Error(
        `${sourceName}: ${field}[${index}] must be a non-empty, trimmed lowercase string`,
      );
    }
    if (!options.validate(entry)) {
      throw new Error(
        `${sourceName}: ${field}[${index}] must contain ${options.expectation}`,
      );
    }
    if (seen.has(entry)) {
      throw new Error(
        `${sourceName}: duplicate ${field} entry ${JSON.stringify(entry)}`,
      );
    }
    seen.add(entry);
    return entry;
  });
}

function generateGo() {
  const lines = [
    "// Code generated by scripts/generate-text-preview-types.mjs. DO NOT EDIT.",
    "// Edit text_preview_types.json and run `pnpm generate:text-preview-types`.",
    "",
    "package handler",
    "",
    "var textPreviewContentTypes = newTextPreviewSet(",
  ];
  for (const contentType of contentTypes) {
    lines.push(`\t${JSON.stringify(contentType)},`);
  }
  lines.push(")", "", "var textPreviewExtensions = newTextPreviewSet(");
  appendGoGroups(lines, extensionGroups);
  lines.push(")", "", "var textPreviewBasenames = newTextPreviewSet(");
  appendGoGroups(lines, basenameGroups);
  lines.push(
    ")",
    "",
    "func newTextPreviewSet(values ...string) map[string]struct{} {",
    "\tset := make(map[string]struct{}, len(values))",
    "\tfor _, value := range values {",
    "\t\tset[value] = struct{}{}",
    "\t}",
    "\treturn set",
    "}",
    "",
  );
  return lines.join("\n");
}

function appendGoGroups(lines, groups) {
  for (const group of groups) {
    lines.push(`\t// ${group.label}`);
    for (const value of group.values) {
      lines.push(`\t${JSON.stringify(value)},`);
    }
  }
}

function generateTypeScript() {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-text-preview-types.mjs.",
    "// Do not edit by hand — edit server/internal/handler/text_preview_types.json",
    "// and run `pnpm generate:text-preview-types`.",
    "",
    "export const TEXT_CONTENT_TYPES: ReadonlySet<string> = new Set([",
  ];
  for (const contentType of contentTypes) {
    lines.push(`  ${JSON.stringify(contentType)},`);
  }
  lines.push(
    "]);",
    "",
    "export const TEXT_EXTENSIONS: ReadonlySet<string> = new Set([",
  );
  appendTypeScriptSetGroups(lines, extensionGroups);
  lines.push(
    "]);",
    "",
    "export const TEXT_BASENAMES: ReadonlySet<string> = new Set([",
  );
  appendTypeScriptSetGroups(lines, basenameGroups);
  lines.push(
    "]);",
    "",
    "export const TEXT_EXTENSION_LANGUAGE_MAP: Readonly<Record<string, string>> = {",
  );
  appendTypeScriptMapGroups(lines, extensionGroups);
  lines.push(
    "};",
    "",
    "export const TEXT_BASENAME_LANGUAGE_MAP: Readonly<Record<string, string>> = {",
  );
  appendTypeScriptMapGroups(lines, basenameGroups);
  lines.push("};", "");
  return lines.join("\n");
}

function appendTypeScriptSetGroups(lines, groups) {
  for (const group of groups) {
    lines.push(`  // ${group.label}`);
    for (const value of group.values) {
      lines.push(`  ${JSON.stringify(value)},`);
    }
  }
}

function appendTypeScriptMapGroups(lines, groups) {
  for (const group of groups) {
    lines.push(`  // ${group.label}`);
    for (const value of group.values) {
      lines.push(`  ${JSON.stringify(value)}: ${JSON.stringify(group.language)},`);
    }
  }
}
