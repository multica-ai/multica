	localUserName           = "陈星耀"
	localWorkspaceName      = "LifeOS"
	localWorkspaceSlug      = "lifeos"
	localWorkspaceBrief     = "AI 星耀的本地日常工作执行看板。"
	localLifeOSCEOAgentName = "AI 星耀"
