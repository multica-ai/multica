const AntigravityOAuthTokenPath = ".gemini/antigravity-cli/antigravity-oauth-token"

const antigravityImageReceiptLimit = 8 << 20

type AntigravityImageResult struct {
	Path        string
	RateLimited bool
}

// The CLI owns refresh; only a host-local link enters the private job home.
func antigravityImageAuth(home string) (string, error) {
	path, err := filepath.EvalSymlinks(filepath.Join(home, AntigravityOAuthTokenPath))
	if err != nil {
		return "", errors.New("Antigravity images require file-backed host authentication")
	}
	raw, err := readAntigravityImageFile(path, 64<<10)
	var auth struct {
		Token struct {
			AccessToken string `json:"access_token"`
		} `json:"token"`
		Method string `json:"auth_method"`
	}
	if err != nil || json.Unmarshal(raw, &auth) != nil || strings.TrimSpace(auth.Token.AccessToken) == "" || (auth.Method != "" && auth.Method != "consumer") {
		return "", errors.New("Antigravity images require a consumer subscription login")
	}
	return path, nil
}

// ProbeAntigravityImages does not start a conversation or spend model quota.
func ProbeAntigravityImages(ctx context.Context, command Command, home string) error {
	if _, err := antigravityImageAuth(home); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	out, err := runAntigravityImageCommand(ctx, command, "", home, "models")
	if err != nil || len(bytes.TrimSpace(out)) == 0 {
		return errors.New("Antigravity model catalog unavailable; host login is not ready")
	}
	return nil
}

type antigravityImageOutput struct {
	bytes.Buffer
	overflow bool
}

func (b *antigravityImageOutput) Write(p []byte) (int, error) {
	n := len(p)
	room := antigravityImageReceiptLimit - b.Len()
	if n > room {
		b.overflow = true
		p = p[:room]
	}
	_, _ = b.Buffer.Write(p)
	return n, nil // Keep draining even if the provider exceeds the receipt limit.
}

func runAntigravityImageCommand(ctx context.Context, command Command, dir, home string, args ...string) ([]byte, error) {
	cmd := command.exec(ctx, args...)
	cmd.Dir = dir
	cmd.Env = buildEnv(map[string]string{"HOME": home, "USERPROFILE": home})
	cmd.Stderr = io.Discard
	cmd.WaitDelay = 2 * time.Second
	var out antigravityImageOutput
	cmd.Stdout = &out
	err := runOwned(cmd, slog.New(slog.NewTextHandler(io.Discard, nil)))
	if ctx.Err() != nil {
		return nil, ctx.Err()
	}
	if out.overflow {
		return nil, errors.New("Antigravity image receipt exceeds size limit")
	}
	return out.Bytes(), err
}

// GenerateAntigravityImage executes once. Upload retries belong to the daemon,
// never to this adapter. Native subagent transcripts, not assistant prose,
// identify the image generated by this conversation.
func GenerateAntigravityImage(ctx context.Context, command Command, sourceHome, dir, prompt string, inputs []string) (AntigravityImageResult, error) {
	ctx, cancel := context.WithTimeout(ctx, 20*time.Minute)
	defer cancel()
	auth, err := antigravityImageAuth(sourceHome)
	if err != nil {
		return AntigravityImageResult{}, err
	}
	dir, err = filepath.EvalSymlinks(dir)
	if err != nil {
		return AntigravityImageResult{}, err
	}
	home := filepath.Join(dir, "agy-home")
	if err := os.Mkdir(home, 0700); err != nil {
		return AntigravityImageResult{}, err
	}
	appData := filepath.Join(home, ".gemini", "antigravity-cli")
	if err := os.MkdirAll(appData, 0700); err != nil {
		return AntigravityImageResult{}, err
	}
	if err := os.Symlink(auth, filepath.Join(home, AntigravityOAuthTokenPath)); err != nil {
		return AntigravityImageResult{}, err
	}
	inputJSON, err := json.Marshal(inputs)
	if err != nil {
		return AntigravityImageResult{}, err
	}
	instruction := "Use the built-in image-generator subagent to produce exactly one final image. Wait for it to finish. Accept the first successful image without refinement or additional generation. Do not use shell commands or external services. For editing, pass the supplied reference paths in generate_image ImagePaths.\nReference ImagePaths: " + string(inputJSON) + "\nImage request:\n" + prompt
	logPath := filepath.Join(dir, "agy.log")
	out, runErr := runAntigravityImageCommand(ctx, command, dir, home,
		"--dangerously-skip-permissions", "--disable-slash-commands", "--output-format", "stream-json",
		"--print-timeout", "20m", "--log-file", logPath, "-p", instruction)
	if ctx.Err() != nil {
		return AntigravityImageResult{}, ctx.Err()
	}
	state, err := parseAntigravityImageStream(out)
	if err != nil {
		return AntigravityImageResult{}, err
	}
	result, err := state.receipt(appData)
	if err != nil {
		return AntigravityImageResult{}, err
	}
	if result.Path != "" {
		return result, nil // A tail error must not replay a successful generation.
	}
	if state.rateLimited || result.RateLimited || antigravityImageLogLimited(dir, logPath) {
		return AntigravityImageResult{RateLimited: true}, nil
	}
	if runErr != nil || !state.completed {
		return AntigravityImageResult{}, errors.New("Antigravity image execution did not complete")
	}
	return AntigravityImageResult{}, errors.New("Antigravity returned no native image receipt")
}

type antigravityImageStream struct {
	parent      string
	child       string
	completed   bool
	rateLimited bool
}

func antigravityImageConversation(id string) bool {
	parsed, err := uuid.Parse(id)
	return err == nil && parsed.String() == id
}

func parseAntigravityImageStream(raw []byte) (antigravityImageStream, error) {
	var state antigravityImageStream
	scanner := newAgentStreamScanner(bytes.NewReader(raw))
	for scanner.Scan() {
		var event struct {
			Event          string `json:"event"`
			ConversationID string `json:"conversation_id"`
			Step           *struct {
				ConversationID string `json:"conversation_id"`
				State          string `json:"state"`
				Type           string `json:"step_type"`
				Tool           string `json:"tool_name"`
				Subagents      *struct {
					Items []struct {
						Type string `json:"type_name"`
						ID   string `json:"conversation_id"`
					} `json:"subagents"`
				} `json:"subagent_info"`
			} `json:"step_update"`
			Result *antigravityStreamResult `json:"result"`
		}
		if json.Unmarshal(scanner.Bytes(), &event) != nil {
			return state, errors.New("invalid Antigravity image event")
		}
		switch event.Event {
		case "init":
			if !antigravityImageConversation(event.ConversationID) || (state.parent != "" && state.parent != event.ConversationID) {
				return state, errors.New("invalid Antigravity image conversation")
			}
			state.parent = event.ConversationID
		case "step_update":
			step := event.Step
			if step == nil || state.parent == "" || step.ConversationID != state.parent || step.State != "DONE" || step.Type != "subagent" || step.Tool != "invoke_subagent" || step.Subagents == nil {
				continue
			}
			for _, child := range step.Subagents.Items {
				if child.Type != "image-generator" {
					continue
				}
				if !antigravityImageConversation(child.ID) || child.ID == state.parent || (state.child != "" && child.ID != state.child) {
					return state, errors.New("ambiguous Antigravity image subagent")
				}
				state.child = child.ID
			}
		case "result":
			if result := event.Result; result != nil && result.ConversationID == state.parent {
				state.completed = result.Status == "SUCCESS"
				state.rateLimited = !state.completed && antigravityImageQuotaError(result.Error)
			}
		}
	}
	return state, scanner.Err()
}

func (s antigravityImageStream) receipt(appData string) (AntigravityImageResult, error) {
	var result AntigravityImageResult
	if s.parent == "" {
		return result, nil
	}
	brain := filepath.Join(appData, "brain")
	artifactRoot := filepath.Join(brain, s.parent)
	for _, id := range []string{s.parent, s.child} {
		if id == "" {
			continue
		}
		// Derive the transcript path from a validated conversation ID. Never
		// follow arbitrary log_uri values supplied by the process.
		path := filepath.Join(brain, id, ".system_generated", "logs", "transcript.jsonl")
		path, err := antigravityImagePathWithin(brain, path)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return result, err
		}
		raw, err := readAntigravityImageFile(path, antigravityImageReceiptLimit)
		if err != nil {
			return result, err
		}
		next, err := parseAntigravityImageTranscript(raw, artifactRoot)
		if err != nil {
			return result, err
		}
		if next.Path != "" {
			if result.Path != "" && result.Path != next.Path {
				return result, errors.New("multiple Antigravity image producers")
			}
			result.Path = next.Path
		}
		result.RateLimited = result.RateLimited || next.RateLimited
	}
	if result.Path != "" {
		result.RateLimited = false
	}
	return result, nil
}

func parseAntigravityImageTranscript(raw []byte, artifactRoot string) (AntigravityImageResult, error) {
	var result AntigravityImageResult
	pending := -1
	scanner := newAgentStreamScanner(bytes.NewReader(raw))
	for scanner.Scan() {
		var step struct {
			Index   int    `json:"step_index"`
			Source  string `json:"source"`
			Type    string `json:"type"`
			Status  string `json:"status"`
			Error   string `json:"error"`
			Content string `json:"content"`
			Calls   []struct {
				Name string `json:"name"`
			} `json:"tool_calls"`
			Media []struct {
				MIME string `json:"mime_type"`
				URI  string `json:"uri"`
			} `json:"media"`
		}
		if json.Unmarshal(scanner.Bytes(), &step) != nil {
			return result, errors.New("invalid Antigravity image transcript")
		}
		if step.Type == "GENERIC" && step.Source == "MODEL" && step.Index == pending {
			pending = -1
			if step.Status == "ERROR" {
				result.RateLimited = result.RateLimited || antigravityImageQuotaError(step.Error)
				continue
			}
			if step.Status != "DONE" {
				continue
			}
			var path string
			if len(step.Media) == 1 && strings.HasPrefix(step.Media[0].MIME, "image/") {
				path = antigravityImageFileURI(step.Media[0].URI)
			} else if len(step.Media) == 0 {
				for _, line := range strings.Split(step.Content, "\n") {
					if value, ok := strings.CutPrefix(line, "Generated image is saved at "); ok {
						path = strings.TrimSuffix(value, ".")
					}
				}
			}
			path, err := antigravityImagePathWithin(artifactRoot, path)
			if err != nil {
				return result, errors.New("Antigravity image artifact is missing or outside its conversation")
			}
			info, err := os.Stat(path)
			if err != nil || !info.Mode().IsRegular() || info.Size() == 0 {
				return result, errors.New("Antigravity image artifact must be a nonempty regular file")
			}
			result.Path = path // Last native success if the subagent retried internally.
			continue
		}
		pending = -1
		if step.Source == "MODEL" && step.Type == "PLANNER_RESPONSE" && step.Status == "DONE" && len(step.Calls) == 1 && step.Calls[0].Name == "generate_image" {
			pending = step.Index + 1
		}
	}
	return result, scanner.Err()
}

func antigravityImageFileURI(value string) string {
	u, err := url.Parse(value)
	if err != nil || u.Scheme != "file" || u.Host != "" || u.RawQuery != "" || u.Fragment != "" {
		return ""
	}
	path := filepath.FromSlash(u.Path)
	if runtime.GOOS == "windows" && len(path) > 2 && path[0] == '\\' && path[2] == ':' {
		path = path[1:]
	}
	return path
}

func antigravityImagePathWithin(root, path string) (string, error) {
	if !filepath.IsAbs(path) {
		return "", errors.New("Antigravity image path must be absolute")
	}
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil {
		return "", err
	}
	// root is derived from the canonical job directory before the process
	// starts. Resolving root here would trust a provider-created escape link.
	rel, err := filepath.Rel(root, resolved)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
		return "", errors.New("Antigravity image path escaped its job directory")
	}
	return resolved, nil
}

func readAntigravityImageFile(path string, limit int64) ([]byte, error) {
	info, err := os.Stat(path)
	if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > limit {
		return nil, errors.New("invalid Antigravity image metadata file")
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	raw, err := io.ReadAll(io.LimitReader(f, limit+1))
	if int64(len(raw)) > limit {
		return nil, errors.New("Antigravity image metadata exceeds size limit")
	}
	return raw, err
}

var antigravityImageQuotaPattern = regexp.MustCompile(`(?i)\b(resource_exhausted|model_capacity_exhausted|individual quota reached|quota exceeded|quota exhausted|usage limit|rate limit|rate_limit|too many requests|(?:code|http|status)\s*[:=]?\s*429)\b`)

func antigravityImageQuotaError(message string) bool {
	return antigravityImageQuotaPattern.MatchString(message)
}

func antigravityImageLogLimited(dir, path string) bool {
	path, err := antigravityImagePathWithin(dir, path)
	if err != nil {
		return false
	}
	raw, err := readAntigravityImageFile(path, antigravityImageReceiptLimit)
	if err != nil {
		return false
	}
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	for scanner.Scan() {
		line := scanner.Text()
		// Only native error diagnostics, never echoed prompts or assistant text.
		if !strings.HasPrefix(line, "E") || !strings.Contains(line, "] ") {
			continue
		}
		_, message, _ := strings.Cut(line, "] ")
		for _, prefix := range []string{"agent executor error:", "error generating image:"} {
			if rest, ok := strings.CutPrefix(message, prefix); ok && antigravityImageQuotaError(rest) {
				return true
			}
		}
	}
	return false
}
