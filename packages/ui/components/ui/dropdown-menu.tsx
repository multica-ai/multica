function DropdownMenuRadioItem({
  className,
  children,
  inset,
  // Base UI defaults radio items to closeOnClick=false (tuned for menus where
  // the user adjusts several options in one visit). Our radio menus are almost
  // all single-select pickers, so selecting should dismiss; menus that mix a
  // radio group with further actions opt back out with closeOnClick={false}.
  closeOnClick = true,
  ...props
}: MenuPrimitive.RadioItem.Props & {
  inset?: boolean
}) {
  return (
    <MenuPrimitive.RadioItem
      data-slot="dropdown-menu-radio-item"
      data-inset={inset}
      closeOnClick={closeOnClick}
      className={cn(
        "relative flex cursor-default items-center gap-2 rounded-menu-item py-1.5 pr-8 pl-2 text-body outline-hidden select-none focus:bg-menu-item-hover focus:text-menu-item-hover-foreground data-inset:pl-8 data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className
      )}
      {...props}
    >
      <span
        className="pointer-events-none absolute right-2 flex items-center justify-center"
        data-slot="dropdown-menu-radio-item-indicator"
      >
        <MenuPrimitive.RadioItemIndicator>
          <CheckIcon
          />
        </MenuPrimitive.RadioItemIndicator>
      </span>
      {children}
    </MenuPrimitive.RadioItem>
  )
}

