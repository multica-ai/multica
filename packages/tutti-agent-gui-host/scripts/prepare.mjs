// Generates what the GUI's sources import and no bundler can produce the same
// way on both apps: its scoped stylesheet and the HTML preview's libraries.
// Both apps run this before they build. Third-party notices go to their public roots.
import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";
import { scopeCssPlugin } from "./scope-css.mjs";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const repositoryRoot = fileURLToPath(new URL("../../..", import.meta.url));
const lockRoot = join(packageRoot, ".build-lock");
const fingerprintFile = join(packageRoot, ".build-fingerprint");
const themeTokensFile = join(packageRoot, ".multica-tokens.css");
const stylesheet = join(packageRoot, "src/styles.css");
const generatedStylesheet = join(packageRoot, "src/agent-gui.generated.css");
const generatedLibraries = join(packageRoot, "src/html-preview/libraries.generated.ts");
const licenseRoots = [
  join(repositoryRoot, "apps/desktop/src/renderer/public/licenses/agent-gui"),
  join(repositoryRoot, "apps/web/public/licenses/agent-gui"),
];

async function acquireLock() {
  const deadline = Date.now() + 180_000;
  while (true) {
    try {
      await mkdir(lockRoot);
      return;
    } catch (error) {
      if (error.code !== "EEXIST") throw error;
      const age = Date.now() - (await stat(lockRoot).catch(() => null))?.mtimeMs;
      if (age > 180_000) {
        await rm(lockRoot, { recursive: true, force: true });
        continue;
      }
      if (Date.now() > deadline) throw new Error("Timed out waiting for the Agent GUI build");
      await new Promise((resolve) => setTimeout(resolve, 200));
    }
  }
}

async function fingerprint() {
  const hash = createHash("sha256");
  async function visit(path) {
    const entry = await stat(path);
    if (entry.isDirectory()) {
      for (const name of (await readdir(path)).sort()) {
        if (["node_modules", "dist", ".git"].includes(name) || name.includes(".generated.")) continue;
        await visit(join(path, name));
      }
    } else {
      hash.update(`${relative(repositoryRoot, path)}:${entry.size}:${entry.mtimeMs}\n`);
    }
  }
  await visit(join(packageRoot, "src"));
  await visit(join(repositoryRoot, "packages/ui/styles"));
  await visit(join(repositoryRoot, "vendor/tutti/packages"));
  for (const name of ["package.json", "scripts/prepare.mjs", "scripts/scope-css.mjs"]) await visit(join(packageRoot, name));
  await visit(join(repositoryRoot, "pnpm-lock.yaml"));
  return hash.digest("hex");
}

async function prepareThemeTokens() {
  const source = await readFile(fileURLToPath(import.meta.resolve("@multica/ui/styles/tokens.css")), "utf8");
  const rootSelector = /^:root(?=\s*\{)/gm;
  const darkSelector = /^\.dark(?=\s*\{)/gm;
  if ([...source.matchAll(rootSelector)].length !== 1 || [...source.matchAll(darkSelector)].length !== 1) {
    throw new Error("The shared Multica palette must contain one :root and one .dark rule");
  }
  // Retain the public token values and Tailwind directives verbatim. Only
  // strengthen the palette scopes above the source :root[data-theme] rules.
  const content = "/* Generated from @multica/ui/styles/tokens.css; do not edit. */\n"
    + source.replace(rootSelector, "html.multica-agent-gui[data-theme]")
      .replace(darkSelector, "html.multica-agent-gui[data-theme].dark");
  if (await readFile(themeTokensFile, "utf8").catch(() => null) !== content) await writeFile(themeTokensFile, content);
}

/** Readers in another process see the old file or the new one, never a partial one. */
async function writeAtomic(path, content) {
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, content);
  await rename(temporary, path);
}

async function buildStylesheet() {
  const source = await readFile(stylesheet, "utf8");
  const result = await postcss([tailwindcss({ base: packageRoot, optimize: false }), scopeCssPlugin()])
    .process(source, { from: stylesheet, to: generatedStylesheet, map: false });
  await writeAtomic(generatedStylesheet, `/* Generated from styles.css by scripts/prepare.mjs; do not edit. */\n${result.css}`);
}

async function buildLibraries() {
  const [chart, d3] = await Promise.all([
    readFile(fileURLToPath(new URL("chart.umd.min.js", import.meta.resolve("chart.js"))), "utf8"),
    readFile(join(dirname(fileURLToPath(import.meta.resolve("d3"))), "../dist/d3.min.js"), "utf8"),
  ]);
  await writeAtomic(generatedLibraries, `// Generated by scripts/prepare.mjs; do not edit.\nexport const libraries = ${JSON.stringify({ chart, d3 })};\n`);
}

async function publishLicenses() {
  for (const target of licenseRoots) {
    await mkdir(join(target, "tutti"), { recursive: true });
    await mkdir(join(target, "html-preview"), { recursive: true });
    await cp(join(repositoryRoot, "vendor/tutti/LICENSE"), join(target, "tutti/LICENSE"));
    await cp(join(repositoryRoot, "vendor/tutti/NOTICE"), join(target, "tutti/NOTICE"));
    await cp(join(repositoryRoot, "vendor/tutti/packages/ui/system/NOTICE"), join(target, "tutti/UI_SYSTEM_NOTICE"));
    await cp(join(dirname(fileURLToPath(import.meta.resolve("chart.js"))), "../LICENSE.md"), join(target, "html-preview/Chart.js-LICENSE.md"));
    await cp(join(dirname(fileURLToPath(import.meta.resolve("d3"))), "../LICENSE"), join(target, "html-preview/D3-LICENSE"));
  }
}

await acquireLock();
try {
  await prepareThemeTokens();
  const current = await fingerprint();
  const previous = await readFile(fingerprintFile, "utf8").catch(() => null);
  const hasOutput = await Promise.all([stat(generatedStylesheet), stat(generatedLibraries)]).then(() => true, () => false);
  if (previous !== current || !hasOutput) {
    await buildStylesheet();
    await buildLibraries();
    await writeFile(fingerprintFile, current);
  }
  await publishLicenses();
} finally {
  await rm(lockRoot, { recursive: true, force: true });
}
