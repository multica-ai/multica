import type { ConfigContext, ExpoConfig } from "expo/config";

export type AppVariant = "development" | "staging" | "production";

interface VariantConfig {
  name: string;
  bundleIdentifier: string;
  scheme: string;
}

export function resolveVariant(value: string | undefined): AppVariant {
  if (value === undefined || value === "" || value === "development") return "development";
  if (value === "staging" || value === "production") return value;
  throw new Error(`APP_ENV must be development, staging, or production (got "${value}").`);
}

// Each variant keeps its own bundle id and URL scheme so all three install side
// by side. Production shares `multica://` with Desktop because the web app's
// "open in app" links use it. The `_<VARIANT>` overrides exist for people who
// sign with an Apple ID outside the Multica team; a single shared override
// would collapse the variants onto one id.
export function variantConfig(variant: AppVariant, env: NodeJS.ProcessEnv): VariantConfig {
  switch (variant) {
    case "production":
      return {
        name: "Multica",
        bundleIdentifier: env.EXPO_BUNDLE_IDENTIFIER_PROD ?? "ai.multica.mobile",
        scheme: "multica",
      };
    case "staging":
      return {
        name: "Multica Staging",
        bundleIdentifier: env.EXPO_BUNDLE_IDENTIFIER_STAGING ?? "ai.multica.mobile.staging",
        scheme: "multica-staging",
      };
    case "development":
      return {
        name: "Multica Dev",
        bundleIdentifier: env.EXPO_BUNDLE_IDENTIFIER_DEV ?? "ai.multica.mobile.dev",
        scheme: "multica-dev",
      };
  }
}

export default ({ config }: ConfigContext): ExpoConfig => {
  const variant = resolveVariant(process.env.APP_ENV);
  const { name, bundleIdentifier, scheme } = variantConfig(variant, process.env);
  return {
    ...config,
    name,
    slug: "multica-mobile",
    version: "0.2.0",
    platforms: ["ios"],
    // No over-the-air update channel; every release ships through a native build.
    updates: { enabled: false },
    orientation: "portrait",
    userInterfaceStyle: "automatic",
    scheme,
    // Full-bleed and opaque; iOS applies its own mask. Generated by scripts/brand/generate.mjs.
    icon: "./assets/icon.png",
    ios: {
      supportsTablet: true,
      bundleIdentifier,
      // Only needed when the signing Apple ID belongs to several teams; unset
      // lets `expo run:ios` pick the identity from the Keychain.
      appleTeamId: process.env.EXPO_APPLE_TEAM_ID,
    },
    plugins: [
      "expo-localization",
      "expo-secure-store",
      "expo-sqlite",
      [
        "expo-build-properties",
        {
          ios: {
            buildReactNativeFromSource: true,
            // Xcode 27 builds require SDK 57's scene runtime.
            enableSceneSupport: true,
          },
        },
      ],
    ],
    extra: { appVariant: variant },
  };
};
