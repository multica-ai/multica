// Same timing as `multica-star-enter` in packages/ui/styles/base.css plus the
// delay web's Inbox Zero gives it.
const RISE = {
  delayMs: 200,
  durationMs: 900,
  easing: Easing.bezier(0.16, 1, 0.3, 1),
};

interface MulticaBleedMarkProps {
  /** Width and height in points. */
  size: number;
  /** react-native-svg does not resolve `currentColor`; pass a THEME value. */
  color: string;
  rises?: boolean;
  /** Position it here, usually absolutely with negative insets. */
  style?: StyleProp<ViewStyle>;
}

export function MulticaBleedMark({ size, color, rises = false, style }: MulticaBleedMarkProps) {
  const progress = useSharedValue(rises ? 0 : 1);
  useEffect(() => {
    if (!rises) return;
    progress.value = withDelay(
      RISE.delayMs,
      withTiming(1, { duration: RISE.durationMs, easing: RISE.easing }),
    );
  }, [progress, rises]);

  // From -45° and 60% scale, transparent, to rest.
  const enter = useAnimatedStyle(() => ({
    opacity: progress.value,
    transform: [
      { rotate: `${-45 * (1 - progress.value)}deg` },
      { scale: 0.6 + 0.4 * progress.value },
    ],
  }));

  return (
    <Animated.View
      pointerEvents="none"
      accessibilityElementsHidden
      importantForAccessibility="no-hide-descendants"
      style={[{ width: size, height: size }, style, enter]}
    >
      <Svg width={size} height={size} viewBox="0 0 100 100">
        <Path d={THIN_STAR} fill={color} />
      </Svg>
    </Animated.View>
  );
}
