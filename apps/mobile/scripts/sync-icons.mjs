// Copies the glyphs the app draws from packages/ui/icons/glyphs.ts, which the
// app cannot import (packages/ui is DOM-only). Run after adding a name below
// or after the shared glyphs change: `pnpm --filter @multica/mobile sync:icons`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "AlertCircle", "Archive", "ArrowUp", "AtSign", "Bell", "Bot", "Calendar", "Check", "CheckCircle2",
  "ChevronDown", "ChevronLeft", "ChevronRight", "ChevronsUpDown", "CircleUser", "Clock", "Filter",
  "FolderKanban", "GitMerge", "GitPullRequest", "GitPullRequestClosed", "GitPullRequestDraft", "Hash",
  "Inbox", "Layers", "ListTodo", "Loader2", "LogOut", "Mail", "MessageSquare", "MoreHorizontal",
  "Paperclip", "Plus", "Quote", "Search", "Settings", "Square", "SquarePen", "Star", "Users", "X", "Zap",
];

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, "../../../packages/ui/icons/glyphs.ts"), "utf8");
const glyphs = new Map();
for (const match of source.matchAll(/^export const (\w+): IconNode = (\[.*\]);$/gm)) {
  glyphs.set(match[1], JSON.parse(match[2]));
}

const lines = NAMES.map((name) => {
  const node = glyphs.get(name);
  if (!node) throw new Error(`packages/ui/icons/glyphs.ts has no glyph named ${name}`);
  const children = node.map(([tag, attrs]) => {
    const { className: _className, ...rest } = attrs;
    return [tag, rest];
  });
  return `  ${name}: ${JSON.stringify(children)},`;
});

writeFileSync(
  join(here, "../src/ui/icons/glyphs.ts"),
  `// Generated by scripts/sync-icons.mjs from packages/ui/icons/glyphs.ts; do not edit.
import type { GlyphNode } from "./glyph-node";

export const glyphs = {
${lines.join("\n")}
} satisfies Record<string, GlyphNode>;
`,
);
