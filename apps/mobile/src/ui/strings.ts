export function stringsFor(locale: SupportedLocale): Strings {
  return locale === "zh-Hans" || locale === "zh-Hant" ? zhHans : en;
}

export const StringsContext = createContext<Strings>(en);

export function useStrings(): Strings {
  return useContext(StringsContext);
}

/** Short relative time for list rows: "now", "5m", "3h", "Yesterday", "4d", then a date. */
export function relativeTime(iso: string, strings: Strings, now: number = Date.now()): string {
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return "";
  const minutes = Math.floor((now - then) / 60_000);
  if (minutes < 1) return strings.time.now;
  if (minutes < 60) return strings.time.minutes(minutes);
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return strings.time.hours(hours);
  const days = Math.floor(hours / 24);
  if (days === 1) return strings.time.yesterday;
  if (days < 7) return strings.time.days(days);
  const date = new Date(then);
  return `${date.getMonth() + 1}/${date.getDate()}`;
}
